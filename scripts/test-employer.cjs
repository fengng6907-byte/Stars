const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const nodes=new Map();
function node(selector){if(!nodes.has(selector))nodes.set(selector,{innerHTML:'',textContent:'',style:{},open:false,close(){this.open=false},showModal(){this.open=true}});return nodes.get(selector)}
class FormDataDemo{constructor(data){this.data=data}get(key){return this.data[key]}}
const context=vm.createContext({console,Date,FormData:FormDataDemo,window:{},location:{hash:''},document:{querySelector:node},setTimeout(){return 1},clearTimeout(){}});
vm.runInContext(fs.readFileSync('dist/app.js','utf8'),context,{filename:'app.js'});
const run=code=>vm.runInContext(code,context);
assert.match(node('#app').innerHTML,/Good afternoon, Sarah/);
assert.match(node('#app').innerHTML,/3 Active Roles/);
assert.match(node('#app').innerHTML,/24 New Matches/);
assert.match(node('#app').innerHTML,/Needs Your Attention/);
assert.match(node('#app').innerHTML,/Why Stars matched them/);
run("viewRoleMatches(1)");
assert.match(node('#app').innerHTML,/Talent discovery/);
assert.match(node('#cards').innerHTML,/Daniel Wong/);
assert.match(node('#cards').innerHTML,/Marcus Tan/);
run("state.search='SaaS';renderCards()");
assert.match(node('#cards').innerHTML,/Daniel Wong/);
assert.doesNotMatch(node('#cards').innerHTML,/Marcus Tan/);
run("state.search='';navigate('overview');toggleSave(4);navigate('shortlist')");
assert.match(node('#cards').innerHTML,/Daniel Wong/);
assert.doesNotMatch(node('#cards').innerHTML,/Sarah Lim/);
run("openCheckIn()");
assert.match(node('#modal').innerHTML,/No Change/);
assert.match(node('#modal').innerHTML,/Rejected/);
run("setCheckInOutcome(1,'No Change')");
assert.equal(run('employerAttention().length'),3);
assert.equal(run('employerDemo.activity[0].label'),'No Change');
run("openRejectionFeedback(4)");
assert.match(node('#modal').innerHTML,/Candidate Withdrew/);
run("submitRejectionFeedback({preventDefault(){},target:{reason:'Skills'}},4)");
assert.equal(run('employerAttention().length'),2);
assert.equal(run('employerDemo.attention.find(i=>i.id===4).reason'),'Skills');
run("createEmployerRole({preventDefault(){},target:{title:'Sales Lead',location:'Singapore',min:'4000',max:'6000',brief:'Own sales',type:'Full-time',arrangement:'Hybrid',availability:'Flexible',mustHave:'B2B',preferred:'SaaS'}})");
assert.equal(run('activeEmployerRoles().length'),4);
assert.match(node('#app').innerHTML,/Sales Lead/);
run("openCloseRole(4)");
assert.match(node('#modal').innerHTML,/Hired Through Stars/);
run("confirmRoleClose({preventDefault(){},target:{outcome:'Hired Through Stars',candidate:'4'}},4)");
assert.equal(run('employerRole(4).closure'),'Hired Through Stars');
assert.equal(run('employerRole(4).hiredTalentId'),4);
run("sendIntro({preventDefault(){},target:{role:'Account Executive',salary:'S$4,500–6,000',message:'Sample role'}},4)");
assert.match(node('#app').innerHTML,/Introduction Sent/);
assert.match(node('#app').innerHTML,/Account Executive/);
run("setMode('talent');navigate('interest')");
assert.match(node('#app').innerHTML,/Accept introduction/);
run("respond(state.requests[0].id,'Accepted');setMode('employer');navigate('pipeline')");
assert.match(node('#app').innerHTML,/Talent Interested/);
assert.match(node('#app').innerHTML,/Accepted/);
run("navigate('settings')");
assert.match(node('#app').innerHTML,/Free/);
assert.match(node('#app').innerHTML,/Collective/);
assert.match(node('#app').innerHTML,/Team/);
console.log('PASS: employer overview, role matches, search, shortlist, check-in, feedback, role creation/closure, introduction, pipeline and settings.');
