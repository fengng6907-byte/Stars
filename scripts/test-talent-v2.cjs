const fs=require('fs'),vm=require('vm'),assert=require('node:assert/strict');
const nodes=new Map();
function node(selector){if(selector==='#talent-form')return null;if(!nodes.has(selector))nodes.set(selector,{innerHTML:'',textContent:'',style:{},value:'',close(){},showModal(){}});return nodes.get(selector)}
const context=vm.createContext({console,Date,Intl,libphonenumber:require('libphonenumber-js/mobile'),window:{},location:{hash:'#profile'},document:{querySelector:node,addEventListener(){},modelContext:undefined},setTimeout(){return 1},clearTimeout(){}});
for(const file of ['phone.js','profile.js','app.js','talent-v2.js'])vm.runInContext(fs.readFileSync(`dist/${file}`,'utf8'),context,{filename:file});
let html=node('#app').innerHTML;
assert.match(html,/My Profile/);
assert.match(html,/Professional headline/);
assert.match(html,/Key achievements/);
assert.match(html,/Employment history/);
assert.match(html,/Privacy & consent/);
vm.runInContext("setMode('talent')",context);
html=node('#app').innerHTML;
assert.match(html,/Profile strength/);
assert.match(html,/Opportunity status/);
assert.match(html,/No live matching feed yet/);
vm.runInContext("talentV2.status='Not Looking';confirmOpportunityStatus()",context);
assert.match(node('#app').innerHTML,/Not Looking/);
vm.runInContext("navigate('preferences')",context);
assert.match(node('#app').innerHTML,/Preferred roles/);
assert.match(node('#app').innerHTML,/What matters to you/);
vm.runInContext("navigate('opportunities')",context);
assert.match(node('#app').innerHTML,/Sample opportunity/);
assert.match(node('#app').innerHTML,/Match score unavailable/);
vm.runInContext("setExampleStage('Interested')",context);
assert.match(node('#app').innerHTML,/Example Technology/);
vm.runInContext("navigate('privacy')",context);
assert.match(node('#app').innerHTML,/no employer authentication, visibility enforcement/);
assert.match(node('#app').innerHTML,/Matched Employers Only/);
assert.match(node('#app').innerHTML,/Hide my profile from/);
vm.runInContext("talentDraft.name='Private Candidate';talentDraft.email='secret@example.com';talentDraft.discovery=true;talentDraft.history=[{company:'Private Employer',position:'Manager',description:'Work',from:'2020-01',to:'2022-01'}];talentV2.visibility='Anonymous';previewEmployer()",context);
assert.match(node('#modal').innerHTML,/Anonymous professional/);
assert.doesNotMatch(node('#modal').innerHTML,/Private Candidate|Private Employer|secret@example.com/);
vm.runInContext("setMode('employer')",context);
assert.match(node('#app').innerHTML,/Good afternoon, Sarah/);
assert.match(node('#app').innerHTML,/Your Active Roles/);
vm.runInContext("navigate('talent')",context);
assert.match(node('#app').innerHTML,/Talent discovery/);
assert.match(node('#cards').innerHTML,/Sarah Lim/);
console.log('PASS: talent overview, status, preferences, opportunity stages and privacy preview preserved; employer mode remains accessible.');
